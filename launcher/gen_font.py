# Bakes glyphs into alpha atlases for the PS4 launcher.
# Noto Sans (SIL Open Font Licence); the PlayStation button symbols come from DejaVu Sans.
import sys, os
from PIL import Image, ImageDraw, ImageFont
NOTO = "/usr/share/fonts/truetype/noto/"
def pick(*names):
    for n in names:
        if os.path.exists(n): return n
    raise SystemExit("missing font: " + names[0])
REG  = pick(NOTO + "NotoSans-Regular.ttf")
SEMI = pick(NOTO + "NotoSans-SemiBold.ttf", NOTO + "NotoSans-Medium.ttf", NOTO + "NotoSans-Bold.ttf")
BOLD = pick(NOTO + "NotoSans-Bold.ttf")
SYM  = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
FONTS = [("font_small", REG, 24), ("font_body", REG, 28), ("font_ui", SEMI, 32),
         ("font_tile", SEMI, 30), ("font_tile_big", BOLD, 44), ("font_head", BOLD, 48), ("font_title", BOLD, 68)]
EXTRA = {1: "✕", 2: "○", 3: "△", 4: "□"}
codes = list(range(32, 127)) + sorted(EXTRA)
out = ["/* Generated by gen_font.py: Noto Sans (OFL) and DejaVu Sans symbols. */",
       "typedef struct { short x, y, w, h, xoff, yoff, adv; } LGlyph;",
       "typedef struct { int size, ascent, atlas_w; const LGlyph *g; const unsigned char *atlas; } LFont;",
       "static int lfont_index(int c) { if (c >= 32 && c < 127) return c - 32; if (c >= 1 && c <= 4) return 95 + c - 1; return 0; }"]
for name, path, size in FONTS:
    f = ImageFont.truetype(path, size)
    fs = ImageFont.truetype(SYM, int(size * 0.8))
    W = 1024; x = y = rowh = 0; boxes = []
    for c in codes:
        font = fs if c in EXTRA else f
        ch = EXTRA.get(c, chr(c))
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(r - l, 0), max(b - t, 0)
        if x + w + 2 > W: x = 0; y += rowh + 2; rowh = 0
        boxes.append((font, ch, x, y, w, h, l, t, round(font.getlength(ch))))
        x += w + 2; rowh = max(rowh, h)
    H = y + rowh + 1
    img = Image.new("L", (W, H), 0); d = ImageDraw.Draw(img)
    for font, ch, gx, gy, w, h, l, t, adv in boxes:
        if w and h: d.text((gx - l, gy - t), ch, font=font, fill=255, anchor="ls")
    data = img.tobytes()
    out.append("static const LGlyph %s_g[] = {%s};" % (name, ",".join("{%d,%d,%d,%d,%d,%d,%d}" % (gx, gy, w, h, l, t, adv) for _, _, gx, gy, w, h, l, t, adv in boxes)))
    out.append("static const unsigned char %s_a[%d] = {%s};" % (name, len(data), ",".join(str(v) for v in data)))
    out.append("static const LFont %s = {%d, %d, %d, %s_g, %s_a};" % (name, size, f.getmetrics()[0], W, name, name))
    sys.stderr.write("%s: %dx%d\n" % (name, W, H))
open(sys.argv[1], "w").write("\n".join(out) + "\n")
